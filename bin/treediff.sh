#!/usr/bin/env bash
# treediff — does the patch series reproduce the working Wine tree, in full?
#
# WHY THE OBVIOUS VERSION OF THIS CHECK IS NOT ENOUGH. The natural audit is
# "for each file the patches touch, does it match?" That question was asked
# three times in one session and missed something every time:
#
#   * the wineusb unixlib enumeration, which existed ONLY in a working tree and
#     was in no patch at all (now upstream/patches/0010)
#   * an RBW-MMCSS block in dlls/avrt/main.c, likewise unshipped
#   * RBW-PAINT and RBW-SESSION instrumentation in d2d1 and mmdevapi
#
# Every one was invisible because the audit was shaped like the patch series,
# and a change that arrives by another route is exactly what such an audit
# cannot see. So this diffs the WHOLE tree and lets the series explain itself.
#
# Usage: bin/treediff.sh [pristine-tree]
#   With no argument it extracts a pristine Wine of the matching version and
#   applies upstream/patches/0*.patch to it.
set -uo pipefail
cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/.."
ROOT="$PWD"
WINE_VER="${WINE_VER:-$(wine --version 2>/dev/null | sed 's/^wine-//;s/ .*//')}"
WORK="${RBW_WINE_BUILD:-$HOME/.cache/rbw-wine-build}/wine-$WINE_VER"
REF="${1:-}"

[[ -d "$WORK" ]] || { echo "no working tree at $WORK"; exit 2; }

if [[ -z "$REF" ]]; then
  REF="$(mktemp -d)/wine-$WINE_VER"
  TARBALL="${RBW_WINE_BUILD:-$HOME/.cache/rbw-wine-build}/wine-$WINE_VER.tar.xz"
  [[ -f "$TARBALL" ]] || { echo "no pristine tarball at $TARBALL"; exit 2; }
  echo "extracting a pristine reference (this takes a moment)..."
  tar -C "$(dirname "$REF")" -xf "$TARBALL"
  for p in "$ROOT"/upstream/patches/0*.patch; do
    (cd "$REF" && patch -p1 -s -f < "$p" >/dev/null 2>&1) \
      || echo "  warning: $(basename "$p") did not apply cleanly"
  done
fi

echo "working tree : $WORK"
echo "reference    : pristine wine-$WINE_VER + upstream/patches/0*.patch"
echo

# Source files only. Build products, generated headers and compiled tools differ
# for reasons that say nothing about the patch series.
mapfile -t diffs < <(
  diff -rq --exclude='*.o' --exclude='*.a' --exclude='*.so' --exclude='*.dll' \
       --exclude='*.sys' --exclude='*.exe' --exclude='Makefile' --exclude='config.*' \
       --exclude='compile_commands.json' --exclude='.git' \
       "$REF" "$WORK" 2>/dev/null \
  | grep '^Files .* differ$' | awk '{print $4}' \
  | grep -E '\.(c|h|spec|in|idl)$' | sed "s|^$WORK/||"
)

if [[ ${#diffs[@]} -eq 0 ]]; then
  echo -e "\033[32mThe patch series reproduces the working tree exactly.\033[0m"
  exit 0
fi

echo "${#diffs[@]} source file(s) diverge from the series:"
echo
ALLOW="$ROOT/upstream/patches/expected-divergence.txt"
rc=0
for f in "${diffs[@]}"; do
  # widl regenerates these during any build and records its own input path in
  # the banner, so they differ for reasons that say nothing about the series.
  if head -1 "$WORK/$f" 2>/dev/null | grep -q 'Autogenerated by WIDL'; then
    printf "  \033[90m%-42s\033[0m generated by widl — ignored\n" "$f"; continue
  fi
  markers=$(diff "$REF/$f" "$WORK/$f" 2>/dev/null | grep '^>' | grep -oE 'RBW-[A-Z0-9]+' | sort -u | tr '\n' ' ')
  # An allowlist a human reviewed, not a guess from comment text. Sniffing for
  # "DEBUG ONLY" classified three genuinely debug-only files as unexplained and
  # would just as happily have waved through a real fix that mentioned it.
  if reason=$(grep -E "^${f//\//\\/}[[:space:]]" "$ALLOW" 2>/dev/null | head -1 | sed "s|^[^[:space:]]*[[:space:]]*||"); [ -n "$reason" ]; then
    printf "  \033[33m%-42s\033[0m expected  %s\n" "$f" "$markers"
    printf "  %-42s   %s\n" "" "$reason"
  else
    printf "  \033[31m%-42s\033[0m NOT IN THE ALLOWLIST  %s\n" "$f" "$markers"
    rc=1
  fi
done
echo
if [[ $rc -eq 0 ]]; then
  echo -e "\033[32mEvery divergence is a reviewed, debug-only entry in upstream/patches/expected-divergence.txt.\033[0m"
  echo "None of it can reach a package: builds come from the series into a clean tree."
else
  echo -e "\033[31mUnreviewed divergence — a fix may exist ONLY in this working tree.\033[0m"
  echo "Capture it as a patch in upstream/, delete it, or add it to"
  echo "upstream/patches/expected-divergence.txt with a reason if it is debug-only."
fi
exit $rc
